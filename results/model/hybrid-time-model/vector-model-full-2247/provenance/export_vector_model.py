#!/usr/bin/env python3
"""Export the frozen sklearn ExtraTrees model as self-contained C++ data."""
import argparse
import csv
import hashlib
from pathlib import Path
import re

import numpy as np
import sklearn
from sklearn.ensemble import ExtraTreesRegressor

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('training',type=Path)
parser.add_argument('--output',type=Path,required=True)
args=parser.parse_args()
rows=list(csv.DictReader(args.training.open()))
keys=sorted((k for k in rows[0] if re.fullmatch(r'x\d+',k)),key=lambda x:int(x[1:]))
if len(keys)!=15:raise ValueError('expected 15 input features')
x=np.array([[float(r[k]) for k in keys] for r in rows]);y=np.log([float(r['ratio']) for r in rows])
model=ExtraTreesRegressor(n_estimators=120,max_depth=10,min_samples_leaf=5,random_state=20261028,n_jobs=1).fit(x,y)
nodes=[];roots=[]
for tree in model.estimators_:
    t=tree.tree_;offset=len(nodes);roots.append(offset)
    for i in range(t.node_count):
        if t.children_left[i]<0:nodes.append((float(t.value[i,0,0]),-1,-1,-1))
        else:nodes.append((float(t.threshold[i]),int(t.children_left[i])+offset,int(t.children_right[i])+offset,int(t.feature[i])))
digest=hashlib.sha256(args.training.read_bytes()).hexdigest()
with args.output.open('w') as f:
    f.write('// Generated by export_vector_model.py; do not edit.\n')
    f.write(f'// training_sha256={digest}; sklearn={sklearn.__version__}; trees={len(roots)}; nodes={len(nodes)}\n')
    f.write('#include "vectorModelCalibration.h"\n#include <cmath>\n#include <cstddef>\n')
    f.write('namespace atspmv { namespace {\nstruct Node { double value; int left, right, feature; };\n')
    f.write('static constexpr Node nodes[] = {\n')
    for value,left,right,feature in nodes:f.write(f'{{{value:.17g},{left},{right},{feature}}},\n')
    f.write('};\nstatic constexpr int roots[] = {')
    f.write(','.join(map(str,roots)));f.write('};\n} // namespace\n')
    f.write('double predictVectorRatio(const std::array<double,15>& features) {\n')
    f.write('  float x[15]; for (int i=0;i<15;++i) x[i]=static_cast<float>(features[i]);\n')
    f.write('  double sum=0; for (int root:roots) { int i=root; while (nodes[i].feature>=0) {\n')
    f.write('    const auto& n=nodes[i]; i=x[n.feature]<=n.value?n.left:n.right; } sum+=nodes[i].value; }\n')
    f.write('  return std::exp(sum/(sizeof(roots)/sizeof(roots[0])));\n}\n} // namespace atspmv\n')
print(f'training_sha256={digest} trees={len(roots)} nodes={len(nodes)} output={args.output}')
