#!/usr/bin/env python3
"""Export the frozen medium-row ExtraTrees model without retraining it."""
import argparse
import hashlib
from pathlib import Path

import joblib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('model', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
model = joblib.load(args.model)
if model.n_features_in_ != 30 or len(model.estimators_) != 100:
    raise ValueError('unexpected model shape')
nodes, roots = [], []
for estimator in model.estimators_:
    tree = estimator.tree_
    offset = len(nodes)
    roots.append(offset)
    for i in range(tree.node_count):
        if tree.children_left[i] < 0:
            nodes.append((float(tree.value[i, 0, 0]), -1, -1, -1))
        else:
            nodes.append((float(tree.threshold[i]), int(tree.children_left[i]) + offset,
                          int(tree.children_right[i]) + offset, int(tree.feature[i])))
with args.output.open('w') as out:
    out.write('// Generated by scripts/analysis/export_medium_model.py; do not edit.\n')
    out.write('// source_model_sha256=' + hashlib.sha256(args.model.read_bytes()).hexdigest() + '\n')
    out.write('#include "mediumRowModel.h"\n#include <cmath>\nnamespace atspmv { namespace {\n')
    out.write('struct Node { double value; int left, right, feature; };\nstatic constexpr Node nodes[] = {\n')
    for value, left, right, feature in nodes:
        out.write(f'{{{value:.17g},{left},{right},{feature}}},\n')
    out.write('};\nstatic constexpr int roots[] = {' + ','.join(map(str, roots)) + '};\n}\n')
    out.write('double predictMediumRowRatio(const std::array<double,30>& features) {\n')
    out.write('  float x[30]; for (int i=0;i<30;++i) x[i]=static_cast<float>(features[i]);\n')
    out.write('  double sum=0; for (int root:roots) { int i=root; while (nodes[i].feature>=0) {\n')
    out.write('    const auto& n=nodes[i]; i=x[n.feature]<=n.value?n.left:n.right; } sum+=nodes[i].value; }\n')
    out.write('  return std::exp(sum/(sizeof(roots)/sizeof(roots[0])));\n}\n}\n')
