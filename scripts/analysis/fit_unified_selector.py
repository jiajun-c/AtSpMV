#!/usr/bin/env python3
"""Fit fixed-candidate time ratios to the default AtBSR on H100 PCIe."""
import csv
import hashlib
import json
import math
import statistics
from pathlib import Path

import numpy as np
import sklearn
from sklearn.ensemble import HistGradientBoostingRegressor
from fit_hybrid_selector import ROOT, OUT, FULL, split, vector

# Tuple: backend, measured configuration, feature tile, partition threshold.
CONFIGS=[
    ('atbsr','3/0/8/128/1/1024',3,1024),
    ('atbsr','0/1/8/128/1/1024',0,1024),
    ('csr_dsm','-1/-1/8/256/1/1024',3,1024),
    ('csr_two_stage','-1/-1/8/256/1/1024',3,1024),
    ('cusparse','CSR_ALG1',3,1024),
    ('hybrid_dsm_atbsr','3/0/8/256/1/1024',3,1024),
    ('hybrid_dsm_atbsr','5/0/8/256/1/1024',5,1024),
    ('hybrid_dsm_atbsr','5/0/8/128/1/4096',5,4096),
]

def main():
    features={(r['dataset'],int(r['threshold'])):r for r in csv.DictReader((OUT/'features.csv').open())}
    names=sorted({name for name,_ in features})
    examples=[]
    for name in names:
        samples={}
        with (FULL/'raw'/f'{name}.csv').open() as f:
            for r in csv.DictReader(f):samples.setdefault((r['backend'],r['config']),[]).append(float(r['us']))
        default=statistics.median(samples[('atbsr','-1/-1/8/128/1/1024')])
        for i,(backend,config,tile,threshold) in enumerate(CONFIGS):
            feat=features[(name,threshold)]
            if backend=='hybrid_dsm_atbsr' and int(feat['long_rows'])==0:continue
            t=statistics.median(samples[(backend,config)])
            examples.append({'name':name,'split':split(name),'id':i,'x':vector(feat,tile),'ratio':t/default})
    models=[];predictions={}
    for i,_ in enumerate(CONFIGS):
        train=[r for r in examples if r['id']==i and r['split']=='train']
        model=HistGradientBoostingRegressor(max_iter=100,max_leaf_nodes=7,min_samples_leaf=12,l2_regularization=1,random_state=20261028)
        model.fit(np.array([r['x'] for r in train]),np.log([r['ratio'] for r in train]));models.append(model)
        subset=[r for r in examples if r['id']==i]
        predicted=np.exp(model.predict(np.array([r['x'] for r in subset])))
        for r,v in zip(subset,predicted):predictions[(r['name'],i)]=float(v)
    by_name={n:[] for n in names}
    for r in examples:by_name[r['name']].append(r)
    # Conservative margin to account for model error; assess both margins on
    # dev, then record the specified one without fitting on dev or holdout.
    experiments={}
    for baseline_gate in (0.90,0.95,1.0):
        for hybrid_gate in (0.85,0.90,0.95):
            result={}
            for subset in ('train','dev','holdout'):
                speeds=[];hybrid=bad=changes=0
                for n in names:
                    if split(n)!=subset:continue
                    options=by_name[n]
                    normal=[r for r in options if r['id']<5]
                    best=min(normal,key=lambda r:predictions[(n,r['id'])])
                    if predictions[(n,best['id'])]>=baseline_gate:choice=None;estimate=1.0
                    else:choice=best;estimate=predictions[(n,best['id'])]
                    dsm=[r for r in options if r['id']>=5]
                    if dsm:
                        besthy=min(dsm,key=lambda r:predictions[(n,r['id'])])
                        if predictions[(n,besthy['id'])]<estimate*hybrid_gate:choice=besthy
                    ratio=1. if choice is None else choice['ratio']
                    if choice:
                        changes+=1;bad+=ratio>1;hybrid+=choice['id']>=5
                    speeds.append(1./ratio)
                result[subset]={'matrices':len(speeds),'changed':changes,'hybrid':hybrid,'slower_than_default':bad,
                                'geomean_speedup':math.exp(statistics.mean(math.log(x) for x in speeds)), 'median_speedup':statistics.median(speeds)}
            experiments[f'{baseline_gate}:{hybrid_gate}']=result
    header=['// Generated by scripts/analysis/fit_unified_selector.py; do not edit.', '#pragma once', '#include <cstddef>', 'namespace atspmv::hybrid_model_data {',
            'struct Node { double value, threshold; int feature, left, right; bool leaf; };',
            'struct Tree { const Node* nodes; };', 'struct Model { double baseline; const Tree* trees; std::size_t count; };']
    for i,model in enumerate(models):
        for tree,pred in enumerate(model._predictors):
            nodes=pred[0].nodes
            if any(n['is_categorical'] for n in nodes):raise ValueError('categorical tree unsupported')
            header.append(f'inline constexpr Node nodes_{i}_{tree}[] = {{')
            for n in nodes:
                header.append('  {'+f"{float(n['value']):.17g},{float(n['num_threshold']):.17g},{int(n['feature_idx'])},{int(n['left'])},{int(n['right'])},{str(bool(n['is_leaf'])).lower()}"+'},')
            header.append('};')
        header.append(f'inline constexpr Tree trees_{i}[] = {{'+','.join('{nodes_'+str(i)+'_'+str(j)+'}' for j in range(len(model._predictors)))+'};')
    header.append('inline constexpr Model models[] = {')
    for i,model in enumerate(models):header.append(f'  {{{float(model._baseline_prediction[0,0]):.17g},trees_{i},sizeof(trees_{i})/sizeof(trees_{i}[0])}},')
    header.extend(['};','} // namespace atspmv::hybrid_model_data',''])
    (ROOT/'include/hybridModelCalibration.h').write_text('\n'.join(header))
    with (OUT/'unified-reference.csv').open('w',newline='') as f:
        w=csv.writer(f);w.writerow(['dataset','candidate','split','prediction_ratio','actual_ratio'])
        for r in examples:w.writerow([r['name'],r['id'],r['split'],predictions[(r['name'],r['id'])],r['ratio']])
    targets_digest=hashlib.sha256()
    for name in names:
        targets_digest.update(name.encode()+b'\0')
        targets_digest.update((FULL/'raw'/f'{name}.csv').read_bytes())
    report={'method':'H100 PCIe warm Graph, pre-optimization fixed candidates; all estimates relative to default AtBSR. Grouped deterministic train/dev/holdout split; no setup cost.',
            'sklearn':sklearn.__version__,'features_sha256':hashlib.sha256((OUT/'features.csv').read_bytes()).hexdigest(),
            'names_sha256':hashlib.sha256((OUT/'names.txt').read_bytes()).hexdigest(),
            'targets_sha256':targets_digest.hexdigest(), 'configs':CONFIGS,'experiments':experiments}
    (OUT/'unified-exploratory.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
