#!/usr/bin/env python3
"""Export an already-fitted ExtraTrees candidate; never retrain or select it."""
import argparse
import hashlib
from pathlib import Path

import joblib

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('model', type=Path)
p.add_argument('--output', type=Path, required=True)
p.add_argument('--variant', choices=('v2', 'graph'), default='v2')
a = p.parse_args()
model = joblib.load(a.model)
if model.n_features_in_ != 39 or len(model.estimators_) != 120:
    raise ValueError('unexpected model shape')
nodes, roots = [], []
for estimator in model.estimators_:
    tree = estimator.tree_
    offset = len(nodes)
    roots.append(offset)
    for i in range(tree.node_count):
        if tree.children_left[i] < 0:
            nodes.append((float(tree.value[i, 0, 0]), -1, -1, -1))
        else:
            nodes.append((float(tree.threshold[i]), int(tree.children_left[i]) + offset,
                          int(tree.children_right[i]) + offset, int(tree.feature[i])))
digest = hashlib.sha256(a.model.read_bytes()).hexdigest()
with a.output.open('w') as f:
    f.write('// Generated by scripts/analysis/export_vector_model_v2.py; do not edit.\n')
    f.write(f'// source_model_sha256={digest}; trees={len(roots)}; nodes={len(nodes)}\n')
    f.write('#include "vectorModelCalibrationV2.h"\n#include <cmath>\n#include <cstddef>\n')
    f.write('namespace atspmv { namespace {\nstruct Node { double value; int left, right, feature; };\n')
    f.write('static constexpr Node nodes[] = {\n')
    for value, left, right, feature in nodes:
        f.write(f'{{{value:.17g},{left},{right},{feature}}},\n')
    f.write('};\nstatic constexpr int roots[] = {')
    f.write(','.join(map(str, roots)))
    f.write('};\n} // namespace\n')
    function = 'predictVectorRatioV2' if a.variant == 'v2' else 'predictVectorRatioGraph'
    f.write(f'double {function}(const std::array<double,39>& features) {{\n')
    f.write('  float x[39]; for (int i=0;i<39;++i) x[i]=static_cast<float>(features[i]);\n')
    f.write('  double sum=0; for (int root:roots) { int i=root; while (nodes[i].feature>=0) {\n')
    f.write('    const auto& n=nodes[i]; i=x[n.feature]<=n.value?n.left:n.right; } sum+=nodes[i].value; }\n')
    f.write('  return std::exp(sum/(sizeof(roots)/sizeof(roots[0])));\n}\n} // namespace atspmv\n')
print(f'model_sha256={digest} trees={len(roots)} nodes={len(nodes)} output={a.output}')
