#!/usr/bin/env python3
"""Export a trained physical model as a hardware-guarded native C++ profile."""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('fit',type=Path)
    parser.add_argument('header',type=Path)
    parser.add_argument('--cold', type=Path)
    args=parser.parse_args()
    names={'launch_us':'launch_ns','dram_eff':'bandwidth_efficiency',
           'l2_factor':'l2_bandwidth_multiplier','tile_cycles':'tile_issue_cycles',
           'warp_cycles':'warp_setup_cycles','shuffle_cycles':'shuffle_step_cycles',
           'atomic_avg_ns':'atomic_ns','atomic_serial_ns':'atomic_serial_ns',
           'saturation_warps':'saturation_warps','cache_capacity_fraction':'cache_capacity_fraction',
           'cache_transition':'cache_transition'}
    lines=['#pragma once','', '#include "tileModel.h"', '', '// Generated by scripts/analysis/export_time_model.py.',
           '// Other GPU geometries use uncalibrated defaults.',
           'namespace atspmv {',
           'inline ModelParameters calibratedModelParameters(const HardwareModel& hw, bool cold = false) {',
           '    ModelParameters p;', '    p.cold_cache = cold;']
    for path in [args.fit]+([args.cold] if args.cold else []):
        report=json.loads(path.read_text());params=report['parameters'];hardware=report['hardware']
        cold=report.get('cache_mode','warm')=='cold'
        lines += ['    // Profile SHA256: '+hashlib.sha256(path.read_bytes()).hexdigest(),
                  f"    if (cold == {'true' if cold else 'false'} && hw.sm_count == {hardware['sm_count']} &&",
                  f"        hw.l2_bytes == {hardware['l2_bytes']} && hw.cc_major == {hardware['cc_major']} &&",
                  f"        hw.cc_minor == {hardware['cc_minor']} &&",
                  f"        std::abs(hw.fp64_lanes_per_cycle - {hardware['fp64_lanes_per_cycle']}) < 0.01) {{"]
        for key,field in names.items():
            value=params[key]*(1000 if key=='launch_us' else 1)
            lines.append(f'        p.{field} = {value:.17g};')
        for i,m in enumerate([1,2,4,8,16,32]):
            lines.append(f'        p.tile_dependency_ns[{i}] = {params[f"tile_ns_{m}"]:.17g};')
        lines += ['        p.calibrated = true;','        return p;', '    }']
    lines += ['    return p;', '}', '} // namespace atspmv', '']
    args.header.parent.mkdir(parents=True,exist_ok=True)
    args.header.write_text('\n'.join(lines))

if __name__=='__main__':main()
